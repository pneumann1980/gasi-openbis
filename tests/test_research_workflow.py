class WorkflowClient(FakeClient):
    def __init__(self):
        super().__init__()
        for type_code,cls in (("EXPERIMENTAL_STEP",SampleType),("ATTACHMENT",DataSetType),("RAW_DATA",DataSetType)):
            properties={"$NAME":"VARCHAR","NOTES":"MULTILINE_VARCHAR"}
            if type_code=="EXPERIMENTAL_STEP":
                properties.update(START_DATE="TIMESTAMP",END_DATE="TIMESTAMP")
            assignments=[dict(propertyType=dict(code=k,dataType=t,vocabulary=None),mandatory=k=="$NAME",
                              plugin=None,registrationDate=None,showInEditView=True) for k,t in properties.items()]
            self.types[type_code]=cls(self,data=dict(code=type_code,autoGeneratedCode=False,propertyAssignments=assignments))
        for code,type_code in (("DUT","SAMPLE"),("REFERENCE","INSTRUMENT"),("GAS","GAS_BOTTLE")):
            ref="/INVENTORY/"+code
            self.samples[ref]={"identifier":ref,"code":code,"type":type_code,"space":"INVENTORY",
                               "experiment":"/INVENTORY/GASI/RESOURCES","props":{"$name":code},"parents":[]}

    def get_experiment(self,path):
        allowed={ob.target_path(t) for t in configuration()["gasi_workflow"]["targets"].values()}
        if path in allowed:
            return NS(identifier=path)
        return super().get_experiment(path)

    def get_dataset_types(self):
        return things([self.types[t] for t in ("RAW_DATA","ATTACHMENT")])

    def get_sample_types(self):
        return things([v for k,v in self.types.items() if k not in ("RAW_DATA","ATTACHMENT")])


class ResearchWorkflowTests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root=Path(self.temp.name)
        self.run=run_fixture(self.root)

    def test_default_upload_does_not_connect_or_prepare_real_data(self):
        with patch("gasi_session.writes_enabled", return_value=False), patch.object(ob,"connect_playground",side_effect=AssertionError("No connection")):
            self.assertIsNone(runmod.upload_workflow()[0])

    def test_scientific_requirements_block_invented_sensor_signal_conditions_and_ambiguous_times(self):
        for change in (
            lambda r:r["dut"].update(identity_confirmed=False),
            lambda r:r["channels"][0].update(object_identifier="/INVENTORY/REFERENCE"),
            lambda r:r["channels"][1].update(object_identifier="/INVENTORY/DUT"),
            lambda r:r["stages"][0]["humidity"].update(quantity="H"),
            lambda r:r["stages"][0]["humidity"].update(saturation_phase="ice",quantity="dew_point",unit="degC"),
            lambda r:r["stages"][0]["humidity"].update(value=float("nan")),
            lambda r:r["stages"][0]["gas"]["components"][0].update(value=float("inf")),
            lambda r:r["times"]["measurement"].update(start="2026-11-13T10:00:00"),
            lambda r:r["source_ranges"][0].update(confirmed=False),
            lambda r:r["reference_assessment"].update(confirmed=False),
        ):
            r=deepcopy(self.run);change(r)
            self.assertTrue(runmod.validate_run(r,self.root))
            with self.assertRaises(ob.CheckFailed):
                runmod.prepare_bundle(r,self.root)

    def test_raw_validation_and_channel_and_record_binding_run_before_upload(self):
        for change in (
            lambda r:r["channels"][0].update(column="NON_EXISTING_SIGNAL"),
            lambda r:r["source_ranges"][0].update(last_record=2),
            lambda r:r["source_ranges"][0].update(utc_offset="+10:00"),
        ):
            r=deepcopy(self.run);change(r)
            with self.assertRaises(ob.CheckFailed):
                runmod.prepare_bundle(r,self.root)
        fixture(self.root/"data/measurements",{"A5B_CH01_mV":"NaN"})
        with self.assertRaises(ob.CheckFailed):
            runmod.prepare_bundle(self.run,self.root)
        fixture(self.root/"data/measurements",{"Datum":"13.11.2026","Uhrzeit":"10:05:00",
                                             "MBW373_FROST_POINT_C":"-10,0","A5B_CH01_mV":""})
        with self.assertRaises(ob.CheckFailed):
            runmod.prepare_bundle(self.run,self.root)

    def test_sources_stay_unchanged_and_private_sources_cannot_enter_package(self):
        original=(self.root/"data/measurements/synthetic.csv").read_bytes()
        for activity in runmod.ACTIVITIES:
            self.run["times"][activity]={"start":"2026-11-13T09:00:00Z","end":"2026-11-13T10:00:00Z"}
        bundle=runmod.prepare_bundle(self.run,self.root)
        self.assertEqual((self.root/"data/measurements/synthetic.csv").read_bytes(),original)
        self.assertEqual(len(bundle["manifest"]["datasets"]),5)
        (self.root/".env").write_text("FAKE_SECRET_NEVER_UPLOAD",encoding="utf-8")
        for value in (".env","../outside.csv","data/datasheets/instrument.pdf"):
            r=deepcopy(self.run);r["files"]["analysis"]=[value]
            self.assertTrue(runmod.validate_run(r,self.root))
        plan=json.loads((bundle["path"]/"plan/plan.json").read_text(encoding="utf-8"))
        context=json.loads((bundle["path"]/"context/context.json").read_text(encoding="utf-8"))
        self.assertIn("stages",plan)
        self.assertNotIn("stages",context,"Recorded channels must not become nominal conditions")

    def test_full_graph_and_every_dataset_are_verified_and_second_run_reuses(self):
        client=WorkflowClient();bundle=runmod.prepare_bundle(self.run,self.root)
        result=runmod.ensure_workflow(client,bundle,configuration())
        self.assertEqual(len(client.created),8)  # three activities, five datasets, no new sensor/resource
        self.assertEqual(len(client.samples),6)  # three existing resources + three activities
        measurement=client.samples[result["objects"]["measurement"]["identifier"]]
        self.assertIn("/INVENTORY/DUT",measurement["parents"])
        self.assertIn("/INVENTORY/GAS",measurement["parents"])
        self.assertIn("/INVENTORY/REFERENCE",measurement["parents"])
        self.assertIn(result["objects"]["preparation"]["identifier"],measurement["parents"])
        for item in result["datasets"]:
            expected_owner=result["objects"][item["activity"]]["identifier"]
            self.assertEqual(client.datasets[item["identifier"]]["sample"],expected_owner)
        again=runmod.ensure_workflow(client,bundle,configuration())
        self.assertEqual(len(client.created),8)
        self.assertTrue(all(not e["created"] for e in again["objects"].values()))
        self.assertTrue(all(not e["created"] for e in again["datasets"]))

    def test_lost_response_after_commit_resumes_without_duplicates(self):
        for step in ("dataset",):
            client=WorkflowClient();bundle=runmod.prepare_bundle(self.run,self.root);client.fail_after=step
            with self.assertRaises(TimeoutError):
                runmod.ensure_workflow(client,bundle,configuration())
            runmod.ensure_workflow(client,bundle,configuration())
            self.assertEqual(len(client.created),8)
        client=WorkflowClient();bundle=runmod.prepare_bundle(self.run,self.root)
        client.fail_after=bundle["manifest"]["key"]+"_MEASUREMENT"
        with self.assertRaises(TimeoutError):
            runmod.ensure_workflow(client,bundle,configuration())
        result=runmod.ensure_workflow(client,bundle,configuration())
        self.assertEqual(len(client.created),8)
        self.assertEqual(len(result["datasets"]),5)

    def test_new_analysis_reuses_measurement_but_changed_acquisition_is_blocked(self):
        client=WorkflowClient();one=runmod.prepare_bundle(self.run,self.root)
        first=runmod.ensure_workflow(client,one,configuration())
        self.run["analysis_id"]="ANALYSIS-2";self.run["software_versions"]["analysis"]="Synthetic v2"
        two=runmod.prepare_bundle(self.run,self.root)
        second=runmod.ensure_workflow(client,two,configuration())
        self.assertEqual(first["objects"]["measurement"]["identifier"],second["objects"]["measurement"]["identifier"])
        self.assertNotEqual(first["objects"]["analysis"]["identifier"],second["objects"]["analysis"]["identifier"])
        self.run["stages"][0]["temperature"]["setpoint_C"]=30
        changed=runmod.prepare_bundle(self.run,self.root)
        before=len(client.created)
        with self.assertRaises(ob.CheckFailed):
            runmod.ensure_workflow(client,changed,configuration())
        self.assertEqual(len(client.created),before)

    def test_wrong_host_target_and_tampered_dataset_block_before_creation(self):
        client=WorkflowClient();bundle=runmod.prepare_bundle(self.run,self.root)
        config=configuration();config["gasi_workflow"]["targets"]["measurement"]["project"]="OTHER"
        with self.assertRaises(ob.CheckFailed):runmod.ensure_workflow(client,bundle,config)
        client.url="https://not-the-playground.example"
        with self.assertRaises(ob.CheckFailed):runmod.ensure_workflow(client,bundle,configuration())
        client.url=ob.PLAYGROUND_HOST
        (bundle["path"]/"plan/plan.json").write_bytes(b"tampered")
        with self.assertRaises(ob.CheckFailed):runmod.ensure_workflow(client,bundle,configuration())
        self.assertFalse(client.created)

    def test_remote_file_changes_are_not_overwritten_and_missing_parents_are_repaired(self):
        client=WorkflowClient();bundle=runmod.prepare_bundle(self.run,self.root)
        result=runmod.ensure_workflow(client,bundle,configuration())
        measurement=result["objects"]["measurement"]["identifier"]
        client.samples[measurement]["parents"]=[]
        runmod.ensure_workflow(client,bundle,configuration())
        self.assertIn("/INVENTORY/DUT",client.samples[measurement]["parents"])
        dataset=result["datasets"][0]["identifier"]
        client.datasets[dataset]["bytes"]=b"changed remotely"
        with self.assertRaises(ob.CheckFailed):
            runmod.ensure_workflow(client,bundle,configuration())
        self.assertEqual(client.datasets[dataset]["bytes"],b"changed remotely")
        self.assertEqual(len(client.created),8)

    def test_incorrect_sensor_and_resource_types_do_not_create_entries(self):
        for reference,bad_type in (("/INVENTORY/DUT","GAS_BOTTLE"),("/INVENTORY/GAS","SAMPLE"),
                                   ("/INVENTORY/REFERENCE","SOP")):
            client=WorkflowClient();client.samples[reference]["type"]=bad_type
            bundle=runmod.prepare_bundle(self.run,self.root)
            with self.assertRaises(ob.CheckFailed):
                runmod.ensure_workflow(client,bundle,configuration())
            self.assertFalse(client.created)


