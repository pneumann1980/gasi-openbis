class Dataset(FakeEntity):
    @property
    def file_list(self):return ["original/"+self.data["filename"]]
    def download(self,*,destination,create_default_folders):
        self.client.downloads+=1
        path=Path(destination)/"original";path.mkdir(exist_ok=True)
        (path/self.data["filename"]).write_bytes(self.data["bytes"])
    def get_parents(self):
        return things([self.client.get_dataset(v) for v in getattr(self,"parents",[])])


class StagedClient(WorkflowClient):
    def __init__(self):
        super().__init__()
        assignments=deepcopy(self.types["EXPERIMENTAL_STEP"].data["propertyAssignments"])
        for code in ("REFERENCE","EXPERIMENTAL_STEP.EXPERIMENTAL_GOALS"):
            assignments.append(dict(propertyType=dict(code=code,dataType="MULTILINE_VARCHAR",vocabulary=None),
                mandatory=False,plugin=None,registrationDate=None,showInEditView=True))
        self.types["EXPERIMENTAL_STEP"]=SampleType(self,data=dict(code="EXPERIMENTAL_STEP",autoGeneratedCode=False,propertyAssignments=assignments))
    def get_dataset(self,id):return Dataset(self,self.datasets[id],True)
    def get_datasets(self,*,type,props):
        return things([{**d,**d["props"]} for d in self.datasets.values() if d["type"]==type])


