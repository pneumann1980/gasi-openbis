class StagedUploadTests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory();self.addCleanup(self.temp.cleanup)
        self.root=Path(self.temp.name);self.run=measurement_fixture(self.root);self.client=StagedClient()
        self.targets=configuration()
    def capture(self):
        return r.ensure_workflow(self.client,r.prepare_bundle(self.run,self.root),self.targets)

    def test_timestamp_write_format_preserves_instant_and_readback_compares_offsets(self):
        self.assertEqual(r.server_timestamp('2026-11-13T11:00:00+01:00'), '2026-11-13 10:00:00 +0000')
        self.assertEqual(r.server_timestamp('2026-07-13T12:00:00+02:00'), '2026-07-13 10:00:00 +0000')
        self.assertEqual(r._time('2026-11-13 11:00:00 +0100'), r._time('2026-11-13T10:00:00Z'))
        result=self.capture()
        obj=self.client.get_sample(result['objects']['measurement']['identifier'])
        expected={k.upper():v for k,v in ob.props(obj).items()}
        obj.props['start_date']='2026-11-13 10:00:00 +0100'
        obj.props['end_date']='2026-11-13 11:00:00 +0100'
        self.assertTrue(r._object_matches(obj, expected))
        obj.props['start_date']='2026-11-13 09:00:00 +0100'
        self.assertFalse(r._object_matches(obj, expected))

    def test_timestamp_boundary_rejects_unknown_timezone_and_unconfirmed_precision(self):
        for value in ('2026-11-13T10:00:00', '2026-11-13T10:00:00.123456Z'):
            with self.assertRaises(ValueError):r.server_timestamp(value)

    def test_measurement_needs_no_preparation_analysis_metadata_or_targets(self):
        self.run.pop("upload_scope")  # Measurement is the library default as well.
        self.run["resources"].pop("software")
        self.run["resources"].pop("sop")
        self.targets["gasi_workflow"]["targets"]={"measurement":self.targets["gasi_workflow"]["targets"]["measurement"]}
        self.assertFalse(r.validate_run(self.run,self.root))
        result=self.capture()
        self.assertEqual(set(result["objects"]),{"measurement"})
        self.assertEqual(len(self.client.created),5) # measurement + raw + plan + context + receipt
        obj=self.client.samples[result["objects"]["measurement"]["identifier"]]
        self.assertNotIn("preparation"," ".join(obj["parents"]).lower())
        self.assertEqual(obj["props"]["reference"],self.run["run_id"])
        self.assertEqual(obj["props"]["experimental_step.experimental_goals"],self.run["purpose"])
        again=self.capture()
        self.assertFalse(again["objects"]["measurement"]["created"])
        self.assertEqual(len(self.client.created),5)

    def test_optional_preparation_has_explicit_reason_and_can_be_reused(self):
        self.run["preparation"]={"mode":"create","independently_released":True,"justification":"Standalone approved synthetic plan"}
        self.run["times"]["preparation"]=self.run["times"]["measurement"]
        result=self.capture()
        self.assertEqual(set(result["objects"]),{"preparation","measurement"})
        reference=result["objects"]["preparation"]["identifier"]
        self.assertIn(reference,self.client.samples[result["objects"]["measurement"]["identifier"]]["parents"])
        # A second distinct original, reusing the already released preparation.
        path=self.root/self.run["files"]["raw_data"][0];path.write_bytes(path.read_bytes().replace(b"12,5",b"13,5"))
        self.run["run_id"]="SYNTHETIC-RUN-02";self.run["preparation"]={"mode":"reuse","identifier":reference}
        self.run["times"].pop("preparation")
        self.targets["gasi_workflow"]["targets"].pop("preparation")
        again=self.capture()
        self.assertEqual(set(again["objects"]),{"measurement"})
        self.assertIn(reference,self.client.samples[again["objects"]["measurement"]["identifier"]]["parents"])

    def test_later_analysis_reads_server_ids_paths_hashes_ranges_and_times(self):
        recorded=self.capture();config=analysis_fixture(recorded)
        # No local measurement config or local raw file needed in the analysis kernel.
        fresh=self.root/"fresh_analysis";(fresh/"data/results").mkdir(parents=True)
        (fresh/"data/results/result.csv").write_text("result\n1\n",encoding="utf-8")
        only_analysis=deepcopy(self.targets)
        only_analysis["gasi_workflow"]["targets"]={"analysis":only_analysis["gasi_workflow"]["targets"]["analysis"]}
        prepared=a.prepare_analysis(config,fresh)
        result=a.ensure_analysis(self.client,prepared,only_analysis)
        stored=next(d for d in self.client.datasets.values() if d["filename"]=="analysis_manifest.json")
        manifest=json.loads(stored["bytes"])
        source=manifest["inputs"][0]
        self.assertNotIn("recorded_metadata_gaps", source)  # Existing described-run manifests stay byte-compatible.
        self.assertEqual(source["dataset_id"],recorded["source_receipt"]["inputs"][0]["dataset_id"])
        self.assertEqual(source["file_path"],"original/synthetic.csv")
        self.assertEqual(source["source_receipt"]["dataset_id"],recorded["source_receipt"]["dataset_id"])
        self.assertEqual(source["record_windows"][0]["first_timestamp_utc"],"2026-11-13T09:05:00+00:00")
        self.assertEqual(source["source_ranges"][0]["first_record"],1)
        self.assertEqual(source["stage_ranges"][0]["stage_id"],"S1")
        owner=self.client.samples[result["analysis"]["identifier"]]
        self.assertIn(recorded["objects"]["measurement"]["identifier"],owner["parents"])
        count=len(self.client.created)
        a.ensure_analysis(self.client,prepared,only_analysis)
        self.assertEqual(len(self.client.created),count)
        config["analysis_id"]="LATER-ANALYSIS-02"
        a.ensure_analysis(self.client,a.prepare_analysis(config,fresh),only_analysis)
        self.assertEqual(sum(s["code"].endswith("_MEASUREMENT") for s in self.client.samples.values()),1)

    def test_multiple_files_and_multiple_measurements(self):
        original=self.root/"data/measurements/synthetic.csv"
        other=self.root/"data/measurements/second.csv";other.write_bytes(original.read_bytes().replace(b"12,5",b"14,5"))
        self.run["files"]["raw_data"].append("data/measurements/second.csv")
        self.run["source_ranges"].append({**self.run["source_ranges"][0],"file":"data/measurements/second.csv"})
        self.run["stage_ranges"].append({**self.run["stage_ranges"][0],"file":"data/measurements/second.csv"})
        first=self.capture();self.assertEqual(len(first["source_receipt"]["inputs"]),2)
        original.write_bytes(original.read_bytes().replace(b"12,5",b"15,5"))
        self.run["run_id"]="SECOND-RUN";self.run["files"]["raw_data"]=self.run["files"]["raw_data"][:1]
        self.run["source_ranges"]=self.run["source_ranges"][:1];self.run["stage_ranges"]=self.run["stage_ranges"][:1]
        second=self.capture()
        config=analysis_fixture(first);config["inputs"]+=second["source_receipt"]["inputs"]
        result=a.ensure_analysis(self.client,a.prepare_analysis(config,self.root),self.targets)
        self.assertEqual(len(result["inputs"]),3)
        self.assertEqual(len(self.client.samples[result["analysis"]["identifier"]]["parents"]),2)

    def test_shared_file_is_previewed_but_not_uploaded_twice(self):
        first=self.capture();count=len(self.client.created)
        self.run["run_id"]="ANOTHER-RUN"
        with self.assertRaises(ob.CheckFailed):self.capture()
        self.assertEqual(len(self.client.created),count)
        self.run["raw_file_policy"]["shared_sources"]=[{"file":"data/measurements/synthetic.csv","run_ids":["R1","R2"]}]
        self.assertTrue(any("Gemeinsame" in v for v in r.validate_run(self.run,self.root)))
        self.assertEqual(len(first["source_receipt"]["inputs"]),1)

    def test_partial_capture_and_analysis_resume_with_native_parents(self):
        self.client.fail_after="dataset"
        with self.assertRaises(TimeoutError):self.capture()
        captured=self.capture();self.assertEqual(len(self.client.created),5)
        config=analysis_fixture(captured);config["native_dataset_parents"]=True
        bundle=a.prepare_analysis(config,self.root)
        with self.assertRaises(ob.CheckFailed):a.ensure_analysis(self.client,bundle,self.targets)
        self.targets["gasi_workflow"]["native_dataset_parents"]={"confirmed":True,"evidence":"SYNTHETIC TEST"}
        self.client.fail_after="dataset"
        with self.assertRaises(TimeoutError):a.ensure_analysis(self.client,bundle,self.targets)
        result=a.ensure_analysis(self.client,bundle,self.targets)
        expected={i["dataset_id"] for i in config["inputs"]}
        for entry in result["results"]:
            self.assertEqual(a._native_ids(self.client.get_dataset(entry["dataset_id"])),expected)
        count=len(self.client.created)
        a.ensure_analysis(self.client,bundle,self.targets)
        self.assertEqual(len(self.client.created),count)

    def test_wrong_provenance_blocks_before_writes(self):
        recorded=self.capture();config=analysis_fixture(recorded);count=len(self.client.created)
        for key,value in (("sha256","0"*64),("file_path","original/wrong.csv")):
            wrong=deepcopy(config);wrong["inputs"][0][key]=value
            with self.assertRaises(ob.CheckFailed):
                a.ensure_analysis(self.client,a.prepare_analysis(wrong,self.root),self.targets)
        wrong=deepcopy(config);wrong["inputs"][0]["source_ranges"][0]["last_record"]=2
        with self.assertRaises(ob.CheckFailed):a.ensure_analysis(self.client,a.prepare_analysis(wrong,self.root),self.targets)
        wrong=deepcopy(config);wrong["inputs"][0]["source_ranges"][0]["file"]="data/measurements/wrong.csv"
        with self.assertRaises(ob.CheckFailed):a.ensure_analysis(self.client,a.prepare_analysis(wrong,self.root),self.targets)
        wrong=deepcopy(config);wrong["inputs"][0]["stage_ranges"]=[]
        with self.assertRaises(ob.CheckFailed):a.ensure_analysis(self.client,a.prepare_analysis(wrong,self.root),self.targets)
        self.assertEqual(len(self.client.created),count)

