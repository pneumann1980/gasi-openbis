class AppClient(StagedClient, InventoryClient):
    def __init__(self):
        super().__init__()
        assignments = self.types['EXPERIMENTAL_STEP'].data['propertyAssignments']
        assignments.append(dict(propertyType=dict(code='EXPERIMENTAL_STEP.EXPERIMENTAL_DESCRIPTION', dataType='MULTILINE_VARCHAR', vocabulary=None),
            mandatory=False, plugin=None, registrationDate=None, showInEditView=True))
        assignments = [dict(propertyType=dict(code=key, dataType='VARCHAR', vocabulary=None), mandatory=True,
            plugin=None, registrationDate=None, showInEditView=True) for key in ('$NAME', 'BAM_OE')]
        self.types['SAMPLE'] = SampleType(self, data=dict(code='SAMPLE', autoGeneratedCode=False, propertyAssignments=assignments))

    def get_experiment(self, path):
        from types import SimpleNamespace
        return SimpleNamespace(**self.collections[path])


def configure(root, client):
    (root / 'config').mkdir(exist_ok=True)
    for template in app.ROOT.glob('config/*.example.json'):
        (root / 'config' / template.name).write_bytes(template.read_bytes())
    cfg = deepcopy(client.cfg)
    cfg['gasi_inventory'] = inventory.default_settings()
    cfg['gasi_inventory']['location'] = dict(code='TEST_EXISTING_LOCATION', confirmed=True, evidence='Synthetic room')
    (root / 'config/playground_test_target.json').write_text(json.dumps(cfg), encoding='utf-8')
    return cfg


class SimpleWorkflowTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        inventory_fixture(self.root)
        self.client = AppClient()
        self.cfg = configure(self.root, self.client)
        switch = patch.object(session, 'SESSION_FILE', self.root / '.env')
        switch.start(); self.addCleanup(switch.stop)
        connection = patch.object(ob, 'connect_playground', return_value=(self.client, 'Synthetic client'))
        connection.start(); self.addCleanup(connection.stop)

    def setup_real(self):
        session.start_session(True)
        result, message = app.setup_project(self.root)
        self.assertIn('bestätigt', message, message)
        self.assertIn('synthetic_test', result, message)
        return result

    def test_default_false_all_entrypoints_preview_without_server_mutation(self):
        result, message = app.setup_project(self.root)
        self.assertIn('Vorschau', message)
        self.assertTrue(result['planned'])
        run = measurement_fixture(self.root)
        cfg = app.configured_targets(self.cfg)
        (self.root / 'config/playground_test_target.json').write_text(json.dumps(cfg), encoding='utf-8')
        (self.root / 'config/gasi_run.json').write_text(json.dumps(run), encoding='utf-8')
        result, message = app.upload_measurement(self.root)
        self.assertIn('Vorschau', message, str(result))
        self.assertIn('manifest_sha256', result)
        self.assertFalse(self.client.created)
        self.assertFalse(self.client.saved)

    def test_setup_repeat_reuses_devices_targets_and_synthetic_run(self):
        first = self.setup_real()
        self.assertTrue(first['synthetic_test']['parent_verified'])
        self.assertEqual(first['devices']['created'], 1)
        counts = len(self.client.saved), len(self.client.created)
        again = self.setup_real()
        self.assertEqual(again['devices']['reuse'], 1)
        self.assertEqual(counts, (len(self.client.saved), len(self.client.created)))
        targets = ob.load_target_config(self.root / 'config/playground_test_target.json')[0]
        self.assertNotIn('approved_scope', targets['gasi_workflow'])
        self.assertIn('gasi_dut', targets)

    def test_setup_can_resume_after_lost_collection_response(self):
        self.client.fail_after = '/8.1_TESTUSER/GASI_TEST/RUNS'
        session.start_session(True)
        result, message = app.setup_project(self.root)
        self.assertIn('unvollständig', message)
        self.setup_real()
        self.assertEqual(len(self.client.saved), len(set(self.client.saved)))

    def test_sensor_is_separate_and_measurement_reuses_it(self):
        self.setup_real()
        run = measurement_fixture(self.root)
        run['dut']['identifier'] = None
        (self.root / 'config/gasi_run.json').write_text(json.dumps(run), encoding='utf-8')
        config = dict(identifier=None, local_id='SYNTHETIC-SENSOR-001', name='Synthetic gas humidity DUT',
                      type='SAMPLE', kind='gas_humidity_sensor', properties={})
        (self.root / 'config/gasi_pruefling.json').write_text(json.dumps(config), encoding='utf-8')
        result, message = dut.manage_dut(self.root)
        self.assertIn('pruefling', result, message)
        identifier = result['pruefling']['identifier']
        self.assertTrue(result['pruefling']['created'])
        again, _ = dut.manage_dut(self.root)
        self.assertFalse(again['pruefling']['created'])
        run = json.loads((self.root / 'config/gasi_run.json').read_text())
        self.assertEqual(run['dut']['identifier'], identifier)
        for channel in run['channels']:
            if channel['role'] == 'dut_signal': channel['object_identifier'] = identifier
        (self.root / 'config/gasi_run.json').write_text(json.dumps(run), encoding='utf-8')
        result, message = app.upload_measurement(self.root)
        self.assertIsNotNone(result.get('verification'), message)
        counts = len(self.client.saved), len(self.client.created)
        result, message = app.upload_measurement(self.root)
        self.assertEqual(counts, (len(self.client.saved), len(self.client.created)))
        session.start_session(False)
        result, message = app.upload_measurement(self.root)
        self.assertIn('Vorschau', message)
        self.assertEqual(counts, (len(self.client.saved), len(self.client.created)))

    def test_unknown_sensor_type_or_foreign_host_cannot_create(self):
        self.setup_real()
        count = len(self.client.created)
        cfg = dict(local_id='SYNTHETIC', name='Synthetic', type='MADE_UP', properties={})
        targets = app.configured_targets(self.cfg)
        with self.assertRaises(ob.CheckFailed): dut.ensure_dut(self.client, cfg, targets)
        self.client.url = 'https://production.invalid'
        with self.assertRaises(ob.CheckFailed): dut.ensure_dut(self.client, cfg, targets)
        self.assertEqual(count, len(self.client.created))

    def test_missing_measurement_is_a_message_not_a_kernel_error(self):
        result, message = app.upload_measurement(self.root)
        self.assertTrue(result['issues'])
        self.assertIn('unvollständig', message)
