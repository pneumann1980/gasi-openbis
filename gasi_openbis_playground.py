def mapped_properties(values, schema, report):
    if not isinstance(values, dict):
        raise CheckFailed("Properties müssen JSON-Objekte sein.")
    assignments = {propkey(a["code"]): a for a in schema["assignments"]}
    mapped = {}
    for key, value in values.items():
        a = assignments.get(propkey(key))
        if a is None:
            raise CheckFailed(f"{schema['code']}: Property {key} ist diesem Typ nicht zugewiesen.")
        if a["code"] in mapped:
            raise CheckFailed("Mehrere Schlüssel bezeichnen dieselbe Property.")
        mapped[a["code"]] = value
        if a["vocabulary"] and value not in (None, ""):
            vocab = report["vocabularies"].get(a["vocabulary"], {})
            if not vocab.get("confirmed") or value not in {t["code"] for t in vocab["terms"]}:
                raise CheckFailed(f"{a['code']}: Wert ist nicht in der bestätigten Werteliste.")
    for a in schema["assignments"]:
        if a["mandatory"] and (mapped.get(a["code"]) is None or str(mapped.get(a["code"])).strip() == ""):
            raise CheckFailed(f"{schema['code']}: Pflichtfeld {a['code']} fehlt.")
    if not any(propkey(k) == "name" and v for k, v in mapped.items()):
        raise CheckFailed(f"{schema['code']}: NAME-Property als stabiler Testmarker erforderlich.")
    return mapped


def validate_target(report, config):
    """Fail closed and return canonical property codes for the write API."""
    if report is None or report.get("host") != PLAYGROUND_HOST:
        raise CheckFailed("Kein bestätigter Playground-Host.")
    if not isinstance(config, dict):
        raise CheckFailed("Lokale Zielkonfiguration fehlt.")
    cfg = deepcopy(config)
    scope = cfg.get("approved_test_scope", {})
    if scope.get("steward_approved") is not True or not str(scope.get("approval_reference", "")).strip():
        raise CheckFailed("FB-8.1-Testbereich mit DSSt abstimmen und Freigabereferenz lokal eintragen.")
    for key in ("lab_notebook", "inventory"):
        path = target_path(cfg.get(key, {}))
        prefix = scope.get(f"{key}_path_prefix", "")
        if not isinstance(prefix, str) or not re.fullmatch(r"/[A-Z0-9_.-]+/[A-Z0-9_.-]+(?:/[A-Z0-9_.-]+)?", prefix):
            raise CheckFailed(f"{key}: freigegebener Projekt-/Collection-Präfix fehlt.")
        if not (path == prefix or path.startswith(prefix + "/")):
            raise CheckFailed(f"{key}: Ziel liegt außerhalb des freigegebenen Testbereichs.")
        target = report.get("targets", {}).get(key, {})
        if not target.get("visible") or target.get("path") != path:
            raise CheckFailed(f"{key}: exakter Collection-Pfad nicht bestätigt.")
    instrument = cfg.get("instrument", {})
    if instrument.get("type") not in ("INSTRUMENT", "TESTING_EQUIPMENT") or cfg.get("dataset_type") != "RAW_DATA":
        raise CheckFailed("Test benötigt INSTRUMENT/TESTING_EQUIPMENT und RAW_DATA.")
    if instrument.get("code") != TEST_INSTRUMENT_CODE or cfg.get("run_code") != TEST_RUN_CODE or cfg.get("dataset_name") != TEST_DATASET_NAME:
        raise CheckFailed("Stabile Testkennung verändert. Vorhandenen Test mit denselben Kennungen fortsetzen.")
    for type_code, family, values, destination, key in (
        (instrument["type"], "object_types", {**instrument.get("properties", {}), "name": instrument.get("name", "")}, instrument, "properties"),
        ("EXPERIMENTAL_STEP", "object_types", cfg.get("run_properties", {}), cfg, "run_properties"),
        ("RAW_DATA", "dataset_types", cfg.get("dataset_properties", {}), cfg, "dataset_properties"),
    ):
        schema = report[family].get(type_code, {})
        if not schema.get("available") or not schema.get("schema_confirmed"):
            raise CheckFailed(f"{type_code}: Typ und vollständige Pflichtfelder nicht bestätigt.")
        destination[key] = mapped_properties(values, schema, report)
        if not re.search(r"test|synthe", name({"props": destination[key]}), re.I):
            raise CheckFailed(f"{type_code}: NAME muss als synthetischer Test gekennzeichnet sein.")
    if name({"props": cfg["dataset_properties"]}) != TEST_DATASET_NAME:
        raise CheckFailed("Dataset-NAME muss der stabilen Testkennung entsprechen.")
    return cfg


def check_write_target(report, config):
    try:
        validate_target(report, config)
        return {"ready": True, "reasons": []}
    except (CheckFailed, TypeError, KeyError, AttributeError) as exc:
        reason = str(exc) if isinstance(exc, CheckFailed) else "Zielkonfiguration hat eine ungültige Struktur."
        return {"ready": False, "reasons": [reason]}


