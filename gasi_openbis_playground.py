class CheckFailed(Exception):
    """Credential-free explanation suitable for notebook output."""


def field(obj, key, default=None):
    return obj.get(key, default) if isinstance(obj, dict) else getattr(obj, key, default)


def records(result):
    # Assignments are a DataFrame; Things must remain pyBIS objects.
    return result.to_dict("records") if hasattr(result, "to_dict") else list(result or [])


def code(value):
    return value if isinstance(value, str) else field(value, "code", "")


def props(obj):
    value = field(obj, "props") or field(obj, "properties") or {}
    return value if isinstance(value, dict) else value.all()


def propkey(key):
    return str(key).lstrip("$").casefold()


def name(obj):
    return next((v for k, v in props(obj).items() if propkey(k) == "name"), "")


def identifier(obj):
    return str(field(obj, "identifier") or field(obj, "permId") or field(obj, "code") or "")


def target_path(group):
    values = [group.get(key, "") for key in ("space", "project", "collection")]
    if not all(isinstance(v, str) and re.fullmatch(r"[A-Z0-9_.-]+", v) for v in values):
        raise CheckFailed("Exakte Space-/Project-/Collection-Codes fehlen (keine Platzhalter oder Schrägstriche).")
    return "/" + "/".join(values)


def load_target_config(path=None):
    path = Path(path) if path is not None else TARGET_CONFIG_PATH
    if not path.is_file():
        return None, f"Zielkonfiguration fehlt: {path.as_posix()}. {TARGET_SETUP_NOTEBOOK} öffnen und Ziele zentral einrichten."
    try:
        config = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(config, dict):
            raise ValueError
        return config, f"Zentrale Zielkonfiguration: {path.as_posix()} (noch keine Instanzbestätigung)."
    except (OSError, ValueError):
        return None, "Zielkonfiguration muss ein lesbares JSON-Objekt sein."


def connect_playground():
    try:
        token = session_value(TOKEN_ENV).strip()
    except SessionConfigError as exc:
        return None, str(exc)
    if not token:
        return None, session_status()
    try:
        with redirect_stdout(io.StringIO()), redirect_stderr(io.StringIO()):
            Openbis = importlib.import_module("pybis").Openbis
            # Constructor uses set_token(..., save_token=False); prevents fallback
            # to an unrelated token cached in ~/.pybis.
            client = Openbis(PLAYGROUND_HOST, token=token, verify_certificates=True, use_cache=False)
            if not client.is_session_active():
                return None, "Zugang abgelehnt/abgelaufen. Playground-Token lokal erneuern."
        return client, "Verbindung zum BAM-Playground bestätigt."
    except ImportError:
        return None, "pyBIS fehlt: python -m pip install -r requirements-playground.txt"
    except Exception:
        return None, "Playground nicht erreichbar oder Zugang abgelehnt. Netzwerk/VPN und Token lokal prüfen."


def type_details(client, family, type_code):
    result = {"code": type_code, "available": False, "schema_confirmed": False, "assignments": []}
    try:
        entity = getattr(client, f"get_{family}_type")(type_code)
        result["available"] = True
        result["auto_generated_code"] = field(entity, "autoGeneratedCode")
        result["show_parents"] = field(entity, "showParents")
        for item in records(entity.get_property_assignments()):
            property_code = code(field(item, "propertyType")) or field(item, "code")
            if not property_code or field(item, "mandatory") is None:
                raise CheckFailed("Property-Assignment unvollständig.")
            prop = client.get_property_type(property_code)
            if not field(prop, "dataType"):
                raise CheckFailed("Property-Datentyp nicht lesbar.")
            result["assignments"].append({"code": property_code,
                "mandatory": bool(field(item, "mandatory")), "data_type": field(prop, "dataType"),
                "vocabulary": code(field(prop, "vocabulary")) or None})
        result["schema_confirmed"] = True
    except Exception:
        result["open_question"] = "Typ/Assignments nicht vollständig lesbar; Deployment/Rechte prüfen."
    return result


def discover_playground(client, config=None):
    """Only get_* calls. Names are hints, never proof of FB membership/write rights."""
    report = {"host": str(client.url).rstrip("/"), "spaces": [], "projects": [], "collections": [],
              "object_types": {}, "dataset_types": {}, "vocabularies": {}, "errors": [], "targets": {},
              "type_catalogues": {}}
    for key, method in (("spaces", "get_spaces"), ("projects", "get_projects"), ("collections", "get_experiments")):
        try:
            for item in records(getattr(client, method)()):
                path = identifier(item)
                label = (name(item) if key == "collections" else "") or field(item, "description", "") or ""
                hint = bool(re.search(r"8[._ -]?1|fb81", f"{path} {label}", re.I))
                report[key].append({"path": path, "label": label, "fb81_candidate": hint,
                                    "type": code(field(item, "type"))})
        except Exception:
            report["errors"].append(f"{key}: nicht vollständig lesbar; Rechte/Verbindung prüfen.")
    for family in ("sample", "dataset", "experiment"):
        try:
            report["type_catalogues"][family] = sorted(code(t) for t in records(getattr(client, f"get_{family}_types")()))
        except Exception:
            report["errors"].append(f"{family}-Typkatalog: nicht vollständig lesbar.")
    for type_code in ("EXPERIMENTAL_STEP", "INSTRUMENT", "TESTING_EQUIPMENT", "SETUP.TEST", "CALIBRATION"):
        report["object_types"][type_code] = type_details(client, "sample", type_code)
    for type_code in ("RAW_DATA", "ATTACHMENT", "ELN_PREVIEW"):
        report["dataset_types"][type_code] = type_details(client, "dataset", type_code)
    vocab_codes = {"BAM_OE", "BAM_LOCATION_COMPLETE", "INSTRUMENT_STATUS", "MEASUREMENT_QUANTITY"}
    for schema in [*report["object_types"].values(), *report["dataset_types"].values()]:
        vocab_codes.update(a["vocabulary"] for a in schema["assignments"] if a["vocabulary"])
    for vocab in sorted(vocab_codes):
        try:
            client.get_vocabulary(vocab)  # An empty search alone does not prove existence.
            terms_result = client.get_terms(vocabulary=vocab)
            # pyBIS Things.__iter__ calls get_term(code), but the real term API
            # needs vocabulary AND code. Read its already-fetched table instead.
            terms = records(field(terms_result, "df", terms_result))
            report["vocabularies"][vocab] = {"confirmed": True, "terms": [
                {"code": field(t, "code"), "label": field(t, "label")} for t in terms]}
        except Exception:
            report["vocabularies"][vocab] = {"confirmed": False, "terms": []}
    for key in ("lab_notebook", "inventory"):
        try:
            path = target_path((config or {}).get(key, {}))
            collection = client.get_experiment(path)
            report["targets"][key] = {"path": path, "visible": identifier(collection) == path}
        except Exception:
            report["targets"][key] = {"visible": False}
    return report


def inspect_playground(config=None):
    """Notebook boundary: no raw exceptions and no invalidation of the supplied token."""
    client, message = connect_playground()
    if client is None:
        return None, message
    try:
        with redirect_stdout(io.StringIO()), redirect_stderr(io.StringIO()):
            report = discover_playground(client, config)
        return report, message
    except Exception:
        return None, "Lesende Prüfung fehlgeschlagen. Verbindung und pyBIS-Version prüfen; Serverdetails unterdrückt."
    # No logout(): a user-supplied session token must remain reusable.


def save_discovery_report(report):
    """Keep the full read-only catalogue locally, including large value lists."""
    if not isinstance(report, dict) or report.get("host") != PLAYGROUND_HOST:
        return "Kein bestätigter Playground-Befund zum Speichern."
    try:
        DISCOVERY_REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
        DISCOVERY_REPORT_PATH.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
        return f"Vollständiger lesender Befund (lokal, außerhalb Git): {DISCOVERY_REPORT_PATH.as_posix()}"
    except OSError:
        return "Lesender Befund konnte lokal nicht gespeichert werden."


